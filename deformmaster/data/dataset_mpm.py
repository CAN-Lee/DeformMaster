def _radius_outlier_keep_mask(pts_np, radius, min_neighbors):
    """Open3D's remove_radius_outlier — keep points with >= min_neighbors
    other points within `radius`. Returns boolean mask of shape [N].
    Removes scattered loners; does not remove dense detached blobs."""
    import open3d as o3d
    pcd = o3d.geometry.PointCloud()
    pcd.points = o3d.utility.Vector3dVector(np.asarray(pts_np, dtype=np.float64))
    _, idx = pcd.remove_radius_outlier(nb_points=int(min_neighbors), radius=float(radius))
    keep = np.zeros(len(pts_np), dtype=bool)
    keep[np.asarray(idx, dtype=np.int64)] = True
    return keep


def _dbscan_largest_keep_mask(pts_np, eps, min_points):
    """DBSCAN cluster -> keep only the largest connected component.
    Catches dense detached blobs that radius_outlier preserves."""
    import open3d as o3d
    pcd = o3d.geometry.PointCloud()
    pcd.points = o3d.utility.Vector3dVector(np.asarray(pts_np, dtype=np.float64))
    labels = np.asarray(pcd.cluster_dbscan(eps=float(eps), min_points=int(min_points)))
    # labels >= 0 are clusters; -1 is noise.
    keep = np.zeros(len(pts_np), dtype=bool)
    valid = labels >= 0
    if not valid.any():
        return keep
    # pick the cluster with the most points
    uniq, counts = np.unique(labels[valid], return_counts=True)
    largest = int(uniq[np.argmax(counts)])
    keep[labels == largest] = True
    return keep

# Dataset for DeformMaster Physics-of-Experts Training.
class DeformMasterDataset(Dataset):
    """
    Dataset for DeformMaster Physics-of-Experts Training.
    Loads data generated by DeformMaster's data processing pipeline (final_data.pkl).
    
    Data Structure in final_data.pkl:
        - object_points: [T, N_surf, 3] (Surface points tracked)
        - object_colors: [T, N_surf, 3]
        - surface_points: [N_other, 3] (Other surface points, static/rigid?) -> Usually combined for simulation
        - interior_points: [N_inner, 3] (Interior filling points for solid simulation)
        - controller_points: [T, N_ctrl, 3] (Hand/Interaction points)
    """
    def __init__(self, cfg, split='train', case_name=None):
        self.cfg = cfg
        self.data_root = cfg.data.root
        self.split = split
        
        if case_name:
            self.scenes = [case_name]
        else:
            self.scenes = self._load_scene_list()
        
        # Cache basic info
        self.max_frames = cfg.mpm.max_frames
        
        # [FIXED] Removed router config dependency
        # Default to a reasonable number if not specified
        self.n_tracks = 1024
        
    def _load_scene_list(self):
        # Scan for directories containing final_data.pkl
        scenes = []
        if not os.path.exists(self.data_root):
            return []
            
        for d in sorted(os.listdir(self.data_root)):
            dir_path = os.path.join(self.data_root, d)
            if os.path.isdir(dir_path) and os.path.exists(os.path.join(dir_path, "final_data.pkl")):
                scenes.append(d)
        return scenes

    def __len__(self):
        return len(self.scenes)

    def __getitem__(self, idx):
        scene_id = self.scenes[idx]
        scene_path = os.path.join(self.data_root, scene_id)
        data_path = os.path.join(scene_path, "final_data.pkl")
        
        # Load final_data.pkl
        with open(data_path, "rb") as f:
            data = pickle.load(f)
            
        # 1. Parse Raw Data
        object_points = torch.tensor(data["object_points"], dtype=torch.float32) # [T, N_surf, 3]
        object_colors = torch.tensor(data["object_colors"], dtype=torch.float32) # [T, N_surf, 3]
        interior_points = torch.tensor(data["interior_points"], dtype=torch.float32) # [N_inner, 3]
        
        # Truncate frames if max_frames is set
        if self.max_frames > 0:
            object_points = object_points[:self.max_frames]
            object_colors = object_colors[:self.max_frames]

        # Optional spatial outlier filter on object_points (cotracker tracks).
        # SAM/cotracker can produce points off the object (fluff, edge bleed,
        # depth bleed); they survive even when GS / mesh-interior fills are
        # disabled because they're already in the PKL. Filter on frame 0 and
        # apply the same keep-mask across all frames so indexing stays stable.
        ofg = getattr(self.cfg.data, 'object_outlier_filter', None)
        if ofg and bool(getattr(ofg, 'enabled', False)) and object_points.shape[1] > 0:
            method = str(getattr(ofg, 'method', 'radius')).lower()
            radius = float(getattr(ofg, 'radius', 0.02))
            min_nb = int(getattr(ofg, 'min_neighbors', 8))
            eps = float(getattr(ofg, 'dbscan_eps', 0.012))
            min_pts = int(getattr(ofg, 'dbscan_min_points', 8))
            pts0 = object_points[0].numpy()

            if method == 'radius':
                keep = _radius_outlier_keep_mask(pts0, radius, min_nb)
                tag = f"radius={radius}, min_neighbors={min_nb}"
            elif method == 'dbscan_largest':
                keep = _dbscan_largest_keep_mask(pts0, eps, min_pts)
                tag = f"dbscan eps={eps}, min_points={min_pts}"
            elif method == 'both':
                keep1 = _dbscan_largest_keep_mask(pts0, eps, min_pts)
                keep2 = _radius_outlier_keep_mask(pts0, radius, min_nb)
                keep = keep1 & keep2
                tag = f"dbscan({eps},{min_pts}) AND radius({radius},{min_nb})"
            else:
                raise ValueError(f"unknown object_outlier_filter.method: {method}")

            n_before = object_points.shape[1]
            n_after = int(keep.sum())
            if n_after > 0 and n_after < n_before:
                idx = torch.from_numpy(np.where(keep)[0])
                object_points = object_points.index_select(1, idx)
                object_colors = object_colors.index_select(1, idx)
                print(f"[outlier_filter] {scene_id}: object_points {n_before} -> {n_after} "
                      f"(method={method}, {tag})")
            
        if "surface_points" in data:
            other_surface_points = torch.tensor(data["surface_points"], dtype=torch.float32) # [N_other, 3]
        else:
            other_surface_points = torch.empty(0, 3)

        if "controller_points" in data and data["controller_points"] is not None:
             controller_points = torch.tensor(data["controller_points"], dtype=torch.float32) # [T, N_ctrl, 3]
             if self.max_frames > 0:
                 controller_points = controller_points[:self.max_frames]
        else:
             controller_points = torch.zeros(object_points.shape[0], 0, 3)

        # Apply Coordinate Frame Flip if needed (Z axis)
        if getattr(self.cfg.data, 'reverse_z', False):
            object_points[..., 2] *= -1.0
            interior_points[..., 2] *= -1.0
            other_surface_points[..., 2] *= -1.0
            controller_points[..., 2] *= -1.0

        # ---------------------------------------------------------------------
        # 2. Prepare Data for Router (Observation Stream)
        # Router only sees the surface (visual observation)
        # ---------------------------------------------------------------------
        
        # Static Stream (First Frame Surface)
        # Simplified Input: [Pos(3), Color(3)] = 6 dims
        pos_0 = object_points[0] # [N_surf, 3]
        col_0 = object_colors[0] # [N_surf, 3]
        N_surf = pos_0.shape[0]
        
        gaussians = torch.cat([pos_0, col_0], dim=-1) # [N_surf, 6]
        
        # Subsample Gaussians for Router
        if gaussians.shape[0] > 10000:
             idx_g = torch.randperm(gaussians.shape[0])[:10000]
             gaussians = gaussians[idx_g]

        # Dynamic Stream (Surface Tracks)
        # [T, N_surf, 3] -> [N_surf, T, 3]
        tracks = object_points.permute(1, 0, 2)
        
        # Subsample Tracks for Router
        if tracks.shape[0] > self.n_tracks:
             idx_t = torch.randperm(tracks.shape[0])[:self.n_tracks]
             tracks = tracks[idx_t]

        # ---------------------------------------------------------------------
        # 3. Prepare Data for MPM Simulation (Physical Model)
        # MPM needs the SOLID volume (Surface + Interior). Optionally add
        # Gaussian dense + new internal when PLY exists: init_pos = pkl + dense + new_internal.
        # ---------------------------------------------------------------------
        # Optional toggles for the two mesh-derived particle sources stored in
        # the PKL during process_data:
        #   data['surface_points']  -> trimesh.sample.sample_surface(mesh, N)
        #   data['interior_points'] -> trimesh.sample.volume_mesh(mesh, 10000)
        # data.use_mesh_surface / use_mesh_interior independently disable each.
        # Defaults are True for backward compatibility.
        use_mesh_surface = bool(getattr(self.cfg.data, 'use_mesh_surface', True))
        use_mesh_interior = bool(getattr(self.cfg.data, 'use_mesh_interior', True))
        parts = [object_points[0]]
        if use_mesh_surface:
            parts.append(other_surface_points)
        else:
            other_surface_points = torch.empty(0, 3)
        if use_mesh_interior:
            parts.append(interior_points)
        else:
            interior_points = torch.empty(0, 3)
        init_pos = torch.cat(parts, dim=0)  # [N_total, 3]

        gaussian_output_dir = getattr(self.cfg.data, 'gaussian_output_dir', None)
        if gaussian_output_dir:
            try:
                from scripts_training_eval.dynamics.gaussian_filling import get_gaussian_ply_path, fill_particles_gaussian
                ply_path = get_gaussian_ply_path(gaussian_output_dir, scene_id)
                if ply_path is not None:
                    _, _, new_internal_pos, new_dense_pos = fill_particles_gaussian(
                        ply_path,
                        grid_n=getattr(self.cfg.data, 'gaussian_grid_n', 80),
                        density_thres=getattr(self.cfg.data, 'gaussian_density_thres', 0.8),
                        search_thres=getattr(self.cfg.data, 'gaussian_search_thres', 0.5),
                        max_particles_per_cell=getattr(self.cfg.data, 'gaussian_max_particles_per_cell', 2),
                        opacity_thres=getattr(self.cfg.data, 'gaussian_opacity_thres', 0.1),
                        padding=0.1,
                    )
                    reverse_z = getattr(self.cfg.data, 'reverse_z', False)
                    to_add = []
                    if new_dense_pos.shape[0] > 0:
                        dense = torch.from_numpy(new_dense_pos).float()
                        if reverse_z:
                            dense[..., 2] *= -1.0
                        to_add.append(dense)
                    if new_internal_pos.shape[0] > 0:
                        internal = torch.from_numpy(new_internal_pos).float()
                        if reverse_z:
                            internal[..., 2] *= -1.0
                        to_add.append(internal)
                    if to_add:
                        init_pos = torch.cat([init_pos] + to_add, dim=0)
                        n_pkl = init_pos.shape[0] - sum(t.shape[0] for t in to_add)
                        # [UPDATED] Include scene_id for better tracking in multi-scene training
                        # and removed global flag to print for each scene.
                        print(f"[DeformMaster] Scene: {scene_id} | MPM particles filled from Gaussian data (dense + new internal), pkl={n_pkl}, added={sum(t.shape[0] for t in to_add)}, total={init_pos.shape[0]}")
            except Exception:
                pass  # fallback to pkl-only init_pos
        
        # Ground Truth for Loss Calculation
        # We only have GT tracks for object_points (surface). 
        
        N_other = other_surface_points.shape[0]
        N_interior = interior_points.shape[0]
        N_pkl = N_surf + N_other + N_interior
        N_gaussian = init_pos.shape[0] - N_pkl

        # ---------------------------------------------------------------------
        # 4. GS Rendering Data (optional, for render loss)
        # ---------------------------------------------------------------------
        render_data = self._load_render_data(scene_id, scene_path, object_points.shape[0])

        return {
            'scene_id': scene_id,
            'gaussians': gaussians,           # [N_g, 6] -> Router Input (Static)
            'tracks': tracks,                 # [N_t, T, 3] -> Router Input (Dynamic)
            'init_pos': init_pos,             # [N_sim, 3] -> MPM Initial State (Surface + Interior)
            'gt_surface_tracks': object_points, # [T, N_surf, 3] -> Loss Target (Surface only)
            'controller_points': controller_points, # [T, N_ctrl, 3] -> Boundary Conditions
            'num_supervised': N_surf,         # Integer, count of surface particles
            'particle_counts': {
                'surface': N_surf,
                'other_surface': N_other,
                'interior': N_interior,
                'gaussian_filled': N_gaussian,
                'total': init_pos.shape[0],
            },
            'render_data': render_data,
        }

    def _load_render_data(self, scene_id, scene_path, T):
        """
        Load camera calibration, GS PLY path, and GT frames for rendering loss.
        Returns None if any required data is missing.
        """
        render_cfg = getattr(self.cfg, 'render_loss', None)
        if render_cfg is None or not getattr(render_cfg, 'enabled', False):
            return None

        # 1. Camera calibration
        calib_path = os.path.join(scene_path, "calibrate.pkl")
        meta_path = os.path.join(scene_path, "metadata.json")
        if not os.path.exists(calib_path) or not os.path.exists(meta_path):
            return None

        with open(calib_path, "rb") as f:
            c2ws = pickle.load(f)  # list of [4,4] numpy arrays

        with open(meta_path, "r") as f:
            meta = json.load(f)

        w2cs = [np.linalg.inv(c2w) for c2w in c2ws]
        intrinsics = np.array(meta["intrinsics"])
        WH = meta["WH"]
        cam_idx = getattr(render_cfg, 'camera_idx', 0)

        # 2. GS PLY path
        gs_ply_path = None
        gaussian_output_dir = getattr(self.cfg.data, 'gaussian_output_dir', None)
        gs_path_override = getattr(render_cfg, 'gs_path', 'auto')
        if gs_path_override and gs_path_override != 'auto':
            gs_ply_path = gs_path_override
        elif gaussian_output_dir:
            try:
                from scripts_training_eval.dynamics.gaussian_filling import get_gaussian_ply_path
                gs_ply_path = get_gaussian_ply_path(gaussian_output_dir, scene_id)
            except Exception:
                pass

        if gs_ply_path is None or not os.path.exists(gs_ply_path):
            return None

        # 3. GT frames (color images for the selected camera)
        color_dir = os.path.join(scene_path, "color", str(cam_idx))
        gt_frame_paths = []
        if os.path.isdir(color_dir):
            for t in range(T):
                frame_path = os.path.join(color_dir, f"{t}.png")
                if os.path.exists(frame_path):
                    gt_frame_paths.append(frame_path)
                else:
                    gt_frame_paths.append(None)

        return {
            'gs_ply_path': gs_ply_path,
            'w2c': np.array(w2cs[cam_idx], dtype=np.float32),    # [4, 4]
            'intrinsic': np.array(intrinsics[cam_idx], dtype=np.float32),  # [3, 3]
            'WH': WH,  # [W, H]
            'gt_frame_paths': gt_frame_paths,
            'camera_idx': cam_idx,
        }


def collate_fn(batch):
    """
    Custom collate.
    """
    return {
        'scene_id': [b['scene_id'] for b in batch],
        'gaussians': torch.stack([b['gaussians'] for b in batch]),
        'tracks': torch.stack([b['tracks'] for b in batch]).permute(0, 2, 1, 3), # [B, N, T, 3] -> [B, T, N, 3]
        'init_pos': torch.stack([b['init_pos'] for b in batch]),
        'gt_surface_tracks': torch.stack([b['gt_surface_tracks'] for b in batch]),
        'controller_points': torch.stack([b['controller_points'] for b in batch]),
        'num_supervised': [b['num_supervised'] for b in batch]
    }
